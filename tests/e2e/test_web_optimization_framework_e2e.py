"""The deployed web client's Optimization framework view against the e2e cluster.

Each test drives the page and reads its outcome back from the live runtime:
search annotations harvested from the web tenant's own searches, the golden
dataset they build, a synthetic run generated by the cluster's optimizer pod
and routed into the approval store, a module optimization run in Argo, and
the XGBoost profile recommender trained on the tenant's spans.
"""

